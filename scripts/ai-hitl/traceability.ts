import * as fs from 'node:fs';
import * as path from 'node:path';
import { parseArgs } from 'node:util';
import type { RequirementFile } from './requirements';
import { loadAllRequirements } from './requirements';
import { parseSpec } from './lib/spec';
import { flattenResults, type PwReport, type ResultEntry } from './lib/results';
import { RESULTS_JSON, readJson, writeText } from './lib/store';
import { isMain } from './lib/cli';

export interface TracedTest {
  file: string;
  title: string;
  reqIds: string[];
  caseId?: string;
}

export interface TraceInput {
  requirements: Array<RequirementFile & { file: string }>;
  specs: Array<{ file: string; source: string }>;
  results?: { entries: ResultEntry[]; startTime?: string };
}

function statusOf(test: TracedTest, input: TraceInput): string {
  const r = input.results?.entries.find(
    e => (test.file === e.file || test.file.endsWith(`/${e.file}`)) && e.title === test.title,
  );
  if (!r) return 'not run';
  const icon = { passed: '✅', failed: '❌', flaky: '🟡', skipped: '⏭️', 'not-run': '⚪', 'not-automated': '📝' }[r.status];
  const date = input.results?.startTime ? ` (${input.results.startTime.slice(0, 10)})` : '';
  return `${icon} ${r.status}${date}`;
}

export function renderTraceability(input: TraceInput): string {
  const tests: TracedTest[] = [];
  const legacy: TracedTest[] = [];
  for (const { file, source } of input.specs) {
    for (const t of parseSpec(source)) {
      const entry = { file, title: t.title, reqIds: t.reqIds, caseId: t.caseId };
      (t.reqIds.length > 0 ? tests : legacy).push(entry);
    }
  }

  const known = new Set(input.requirements.flatMap(r => r.items.map(i => i.id)));
  const esc = (s: string) => s.replace(/\|/g, '\\|');
  const out: string[] = [];
  out.push('# Traceability matrix');
  out.push('');
  out.push('> Generated by `npm run ai:trace` from `requirements/*.md`, `@req:` tags in `tests/**/*.spec.ts`');
  out.push(`> and \`${RESULTS_JSON}\` (last local/CI run). Do not edit by hand.`);
  out.push('');

  out.push('## Coverage by resource');
  out.push('');
  out.push('| Resource | Requirements | Covered | Coverage |');
  out.push('| --- | --- | --- | --- |');
  const uncovered: Array<{ id: string; priority: string; text: string; file: string }> = [];
  let totalReq = 0;
  let totalCovered = 0;
  for (const r of input.requirements) {
    const covered = r.items.filter(i => tests.some(t => t.reqIds.includes(i.id)));
    r.items.filter(i => !covered.includes(i)).forEach(i => uncovered.push({ ...i, file: r.file }));
    totalReq += r.items.length;
    totalCovered += covered.length;
    const pct = r.items.length ? Math.round((covered.length / r.items.length) * 100) : 0;
    out.push(`| [${r.resource}](../${r.file}) | ${r.items.length} | ${covered.length} | ${pct}% |`);
  }
  out.push(`| **total** | ${totalReq} | ${totalCovered} | ${totalReq ? Math.round((totalCovered / totalReq) * 100) : 0}% |`);
  out.push('');

  out.push('## Requirements → tests');
  out.push('');
  out.push('| Requirement ID | Priority | Text | Tests | Last status |');
  out.push('| --- | --- | --- | --- | --- |');
  for (const r of input.requirements) {
    for (const i of r.items) {
      const ts = tests.filter(t => t.reqIds.includes(i.id));
      const testCell = ts.length ? ts.map(t => `\`${t.file}\` › ${esc(t.title)}`).join('<br>') : '—';
      const statusCell = ts.length ? ts.map(t => statusOf(t, input)).join('<br>') : '❗ uncovered';
      out.push(`| ${i.id} | ${i.priority} | ${esc(i.text)} | ${testCell} | ${statusCell} |`);
    }
  }
  out.push('');

  out.push('## Uncovered requirements');
  out.push('');
  if (uncovered.length === 0) out.push('None 🎉');
  for (const u of uncovered) out.push(`- **${u.id}** (${u.priority}) — ${u.text} _(${u.file})_`);
  out.push('');

  const orphans = tests.flatMap(t => t.reqIds.filter(id => !known.has(id)).map(id => ({ id, t })));
  if (orphans.length > 0) {
    out.push('## Tags referencing unknown requirements');
    out.push('');
    for (const o of orphans) out.push(`- \`@req:${o.id}\` in \`${o.t.file}\` › ${o.t.title}`);
    out.push('');
  }

  out.push('## Legacy, untraced tests');
  out.push('');
  out.push('Hand-written tests without `@req:` tags. They are not edited by the AI tooling; add tags manually to trace them.');
  out.push('');
  out.push('| File | Test | Last status |');
  out.push('| --- | --- | --- |');
  for (const t of legacy) out.push(`| \`${t.file}\` | ${esc(t.title)} | ${statusOf(t, input)} |`);
  out.push('');
  return out.join('\n');
}

export function findSpecs(dir = 'tests'): Array<{ file: string; source: string }> {
  const out: Array<{ file: string; source: string }> = [];
  const walk = (d: string) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const p = path.posix.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith('.spec.ts')) out.push({ file: p, source: fs.readFileSync(p, 'utf-8') });
    }
  };
  if (fs.existsSync(dir)) walk(dir);
  return out;
}

// npm run ai:trace [-- --out docs/TRACEABILITY.md] [--results test-results/results.json]
if (isMain(import.meta.url)) {
  const { values } = parseArgs({
    options: {
      out: { type: 'string', default: 'docs/TRACEABILITY.md' },
      results: { type: 'string', default: RESULTS_JSON },
    },
  });
  let results: TraceInput['results'];
  if (values.results && fs.existsSync(values.results)) {
    const report = readJson<PwReport>(values.results);
    results = { entries: flattenResults(report), startTime: report.stats?.startTime };
  }
  const md = renderTraceability({ requirements: loadAllRequirements(), specs: findSpecs(), results });
  writeText(values.out as string, md);
  console.log(`• traceability matrix written to ${values.out}${results ? '' : ` (no ${values.results}, statuses = "not run")`}`);
}
